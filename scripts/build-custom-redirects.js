// scripts/build-custom-redirects.js
const fs = require("fs");
const path = require("path");
const { createRedirectPage } = require("./generate-html-redirect");

const configPath = path.join(__dirname, "..", "redirect-config.json");
const config = JSON.parse(fs.readFileSync(configPath, "utf8"));
const customFile = path.join(
  __dirname,
  "..",
  config.customRedirectsFile || "redirect-custom.json",
);

// 自定义短链接的输出根目录（直接放在 public 下）
const CUSTOM_OUTPUT_ROOT = "./public";
const GITIGNORE_FILE = path.join(__dirname, "..", ".gitignore");

// 标记块标识
const BLOCK_START = "# Custom redirects generated by build-custom-redirects.js";
const BLOCK_END = "# End of custom redirects";

function buildCustomRedirects() {
  const customMap = {};
  if (!fs.existsSync(customFile)) {
    console.log("No custom redirects file found, skipping.");
    return customMap;
  }
  const data = JSON.parse(fs.readFileSync(customFile, "utf8"));
  const shortCodes = [];
  for (const [shortCode, targetUrl] of Object.entries(data)) {
    if (customMap[shortCode]) {
      throw new Error(`Duplicate custom shortCode: "${shortCode}"`);
    }
    customMap[shortCode] = targetUrl;
    // 生成页面，输出到 CUSTOM_OUTPUT_ROOT 下（支持多层路径）
    createRedirectPage(shortCode, targetUrl, CUSTOM_OUTPUT_ROOT);
    console.log(`Custom: /${shortCode} -> ${targetUrl}`);
    shortCodes.push(shortCode);
  }

  // 保存自定义映射表
  const mapFile = path.join(
    __dirname,
    "..",
    ".redirects",
    "custom-redirect-map.json",
  );
  fs.mkdirSync(path.dirname(mapFile), { recursive: true });
  fs.writeFileSync(mapFile, JSON.stringify(customMap, null, 2), "utf8");
  console.log(`Custom redirect map saved to ${mapFile}`);

  // 更新 .gitignore
  updateGitignore(shortCodes);

  return customMap;
}

/**
 * 更新 .gitignore 文件，添加自定义短码路径的忽略规则
 * @param {string[]} shortCodes - 所有自定义短码（可能包含路径如 'dev/gitee'）
 */
function updateGitignore(shortCodes) {
  let gitignoreContent = "";
  if (fs.existsSync(GITIGNORE_FILE)) {
    gitignoreContent = fs.readFileSync(GITIGNORE_FILE, "utf8");
  }

  // 构建新的块内容
  const newBlockLines = [
    BLOCK_START,
    ...shortCodes.map((code) => `${code}/`), // 忽略整个目录（如 /dev/gitee/）
    BLOCK_END,
  ];
  const newBlock = newBlockLines.join("\n");

  // 尝试查找已有块
  const blockRegex = new RegExp(`${BLOCK_START}[\\s\\S]*?${BLOCK_END}`, "g");
  let updatedContent;
  if (blockRegex.test(gitignoreContent)) {
    // 替换已有块
    updatedContent = gitignoreContent.replace(blockRegex, newBlock);
  } else {
    // 追加到末尾（确保末尾有换行）
    if (gitignoreContent.length > 0 && !gitignoreContent.endsWith("\n")) {
      gitignoreContent += "\n";
    }
    updatedContent = gitignoreContent + newBlock + "\n";
  }

  fs.writeFileSync(GITIGNORE_FILE, updatedContent, "utf8");
  console.log(
    `Updated .gitignore with custom redirect paths (${shortCodes.length} entries)`,
  );
}

if (require.main === module) {
  buildCustomRedirects();
}

module.exports = { buildCustomRedirects };
